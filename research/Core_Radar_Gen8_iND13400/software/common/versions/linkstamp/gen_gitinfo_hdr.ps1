$status = Get-Content -Path bazel-out/*-status.txt
ForEach($line in $status)
{

    # If the value starts with 0x, we assume it is hex and decode it as such.
    # It is up to the script that generates the *-status files to make sure
    # hex values are preceeded with 0x, otherwise it would be impossible
    # to tell the difference between hex values that don't contain A-F and an integer
    if ($line -match '^(?<macro>\w+) (?<value>0x[0-9a-fA-F]+[uU]?$)')
    {
        Write-Host "#define " $Matches.macro $Matches.value
    }
    # If the value is an integer, we don't need to add quotes
    elseif ($line -match '^(?<macro>\w+) (?<value>\d+$)')
    {
        Write-Host "#define " $Matches.macro $Matches.value
    }
    # Otherwise add quotes around the value
    elseif ($line -match '^(?<macro>\w+) (?<value>.*)')
    {
        $value = $Matches.value # Assign to temp varibale, because Powershell doesn't like a map inside quotes
        Write-Host "#define " $Matches.macro `"${value}`"
    }
}
Write-Host
Write-Host "#endif"
