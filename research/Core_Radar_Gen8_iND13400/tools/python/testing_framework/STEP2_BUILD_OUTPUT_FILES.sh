run_build() {
  local label="$1"
  shift
  local cmd="$BZL build $*"
  LAST_CMD="$cmd"
  LAST_CMD_LABEL="$label"
  echo ""
  echo -e "  ${CYAN}[BUILD]${NC} $label"
  echo "  Command: $cmd"
  echo ""
  # Remove stale bazel-bin dir/symlink so Bazel can recreate its symlink
  rm -rf "$REPO_ROOT/bazel-bin" 2>/dev/null || true
  set +e
  eval "$cmd"
  local exit_code=$?
  set -e
  post_build $exit_code
}

run_cmd() {
  local label="$1"
  shift
  local cmd="$BZL $*"
  echo ""
  echo -e "  ${CYAN}[$label]${NC}"
  echo "  Command: $cmd"
  echo ""
  # Remove stale bazel-bin dir/symlink so Bazel can recreate its symlink
  rm -rf "$REPO_ROOT/bazel-bin" 2>/dev/null || true
  set +e
  eval "$cmd"
  local exit_code=$?
  set -e
  post_build $exit_code
}

post_build() {
  local exit_code=$1
  echo ""
  if [ $exit_code -eq 0 ]; then
    echo -e "  ${GREEN}[SUCCESS]${NC} Build completed successfully."
    # Create Windows-accessible junction for bazel-bin/bazel-out
    create_windows_links
  else
    echo -e "  ${RED}[FAILED]${NC} Build failed with error code: $exit_code"
  fi
  post_build_menu
}

# Create Windows-compatible directory junctions so build outputs are accessible
# from Windows Explorer (Linux symlinks on NTFS aren't visible to Windows)
create_windows_links() {
  # Only needed when running in WSL on a Windows filesystem
  if [[ "$OSTYPE" != "linux-gnu"* ]]; then
    return
  fi

  # Resolve the output base from the execroot symlink Bazel always creates
  local execroot_link="$REPO_ROOT/bazel-Core_Radar_Gen8_iND13400"
  if [ ! -L "$execroot_link" ]; then
    # Try alternate name patterns Bazel might use
    execroot_link=$(find "$REPO_ROOT" -maxdepth 1 -name "bazel-*" -type l ! -name "bazel-bin" ! -name "bazel-out" ! -name "bazel-testlogs" | head -1)
  fi

  if [ -z "$execroot_link" ] || [ ! -L "$execroot_link" ]; then
    echo -e "  ${YELLOW}[WARN]${NC} No Bazel execroot symlink found - cannot create output links."
    return
  fi

  local execroot
  execroot=$(readlink -f "$execroot_link")
  local bin_outputs="$execroot/bazel-out/k8-fastbuild/bin/outputs"

  if [ ! -d "$bin_outputs" ]; then
    # Fall back to searching for the outputs directory
    bin_outputs=$(find "$execroot/bazel-out" -maxdepth 3 -path "*/bin/outputs" -type d 2>/dev/null | head -1)
  fi

  if [ -z "$bin_outputs" ] || [ ! -d "$bin_outputs" ]; then
    echo -e "  ${YELLOW}[WARN]${NC} Build outputs directory not found in Bazel output tree."
    return
  fi

  # If repo is on /mnt/* (Windows drive), replicate the same folder structure
  # as a Windows build: bazel-bin/ contains outputs/, software/, external/, temp/, etc.
  if [[ "$REPO_ROOT" == /mnt/* ]]; then
    local bin_dir
    bin_dir=$(dirname "$bin_outputs")

    # Remove Bazel's symlink (points to Linux FS, not accessible from Windows)
    rm -f "$REPO_ROOT/bazel-bin" 2>/dev/null

    # Copy full bin directory to match Windows bazel-bin structure
    cp -r "$bin_dir" "$REPO_ROOT/bazel-bin" 2>/dev/null \
      && echo -e "  ${GREEN}[OUTPUT]${NC} Build outputs copied to: bazel-bin/" \
      && echo -e "  ${CYAN}        ${NC} (same structure as Windows build - accessible from Explorer)" \
      && echo -e "  ${CYAN}        ${NC} Contents: outputs/ software/ external/ temp/"
  else
    # Native Linux filesystem - just create a symlink
    local bin_dir
    bin_dir=$(dirname "$bin_outputs")
    rm -f "$REPO_ROOT/bazel-bin" 2>/dev/null
    ln -sf "$bin_dir" "$REPO_ROOT/bazel-bin" 2>/dev/null
    echo -e "  ${GREEN}[OUTPUT]${NC} bazel-bin -> $bin_dir"
  fi
}

post_build_menu() {
  # Flush any buffered terminal escape sequences (e.g. cursor position reports)
  # that Windows Terminal + WSL may inject as spurious input
  read -r -t 0.1 -n 1000 _ 2>/dev/null || true
  echo ""
  echo "  ========================================"
  echo "   What would you like to do next?"
  echo "  ========================================"
  if [ -n "$LAST_CMD" ]; then
    echo "    R)  Retry last build: $LAST_CMD_LABEL"
    echo "    V)  Retry with --verbose_failures"
  fi
  echo "    M)  Back to Main Menu"
  echo "    0)  Exit"
  echo "  ========================================"
  read -rp "  Select [R/V/M/0]: " post_choice
  case "${post_choice^^}" in
    R)
      if [ -z "$LAST_CMD" ]; then
        echo "  [ERROR] No previous command to retry."
        post_build_menu
      else
        echo ""
        echo -e "  ${CYAN}[RETRY]${NC} $LAST_CMD_LABEL"
        echo "  Command: $LAST_CMD"
        echo ""
        set +e
        eval "$LAST_CMD"
        local rc=$?
        set -e
        post_build $rc
      fi
      ;;
    V)
      if [ -z "$LAST_CMD" ]; then
        echo "  [ERROR] No previous command to retry."
        post_build_menu
      else
        echo ""
        echo -e "  ${CYAN}[RETRY+VERBOSE]${NC} $LAST_CMD_LABEL"
        echo "  Command: $LAST_CMD --verbose_failures"
        echo ""
        set +e
        eval "$LAST_CMD --verbose_failures"
        local rc=$?
        set -e
        post_build $rc
      fi
      ;;
    M) main_menu ;;
    0) exit 0 ;;
    *)
      echo "  [ERROR] Invalid selection."
      post_build_menu
      ;;
  esac
}

custom_build() {
  echo ""
  echo "  ====== Custom Build Configuration ======"
  echo ""

  # --- Step 1: Pick config variant ---
  echo "  Select platform config:"
  echo "    1) FLR8"
  echo "    2) SRR8P"
  read -rp "  Config [1-2]: " cfg_choice
  case "$cfg_choice" in
    1) CONFIG="--config=flr8" ;;
    2) CONFIG="--config=srr8p" ;;
    *)
      echo "  [ERROR] Invalid config."
      return
      ;;
  esac
  echo ""

  # --- Step 2: Pick vehicle communication ---
  echo "  Select vehicle communication variant:"
  echo "    1) CAN        (default)"
  echo "    2) SomeIP     (Ethernet high-det)"
  echo "    3) None       (standalone / tracker)"
  echo "    4) AL CAN Standalone  (SRR8P only)"
  read -rp "  VehCom [1-4]: " veh_choice
  VEH_COM=""
  case "$veh_choice" in
    1) VEH_COM="--veh_com=can" ;;
    2) VEH_COM="--veh_com=someip" ;;
    3) VEH_COM="--veh_com=none" ;;
    4) VEH_COM="--veh_com=al_can_standalone" ;;
  esac
  echo ""

  # --- Step 3: Tracker variant ---
  TRACKER=""
  if [ "$veh_choice" == "3" ]; then
    echo "  Select tracker variant:"
    echo "    1) platform_flr8_standalone"
    echo "    2) platform_srr8p_standalone"
    echo "    3) platform_srr8p_2_sensor_fusion"
    echo "    4) disabled"
    echo "    5) partner_sensor"
    echo "    6) Skip (none)"
    read -rp "  Tracker [1-6]: " trk_choice
    case "$trk_choice" in
      1) TRACKER="--tracker_variant=platform_flr8_standalone" ;;
      2) TRACKER="--tracker_variant=platform_srr8p_standalone" ;;
      3) TRACKER="--tracker_variant=platform_srr8p_2_sensor_fusion" ;;
      4) TRACKER="--tracker_variant=disabled" ;;
      5) TRACKER="--tracker_variant=partner_sensor" ;;
    esac
    echo ""
  fi
  if [ "$veh_choice" == "4" ]; then
    TRACKER="--tracker_variant=AL --enable_features=true"
  fi

  # --- Step 4: Board and MARS revision ---
  read -rp "  Board version [EDU/A0/B0/A2P4] (default=B0, Enter to skip): " BOARD_VER
  BOARD_FLAG=""
  [ -n "$BOARD_VER" ] && BOARD_FLAG="--chandra_hw_rev=$BOARD_VER"

  read -rp "  MARS HW revision [A0/B0] (default=B0, Enter to skip): " MARS_VER
  MARS_FLAG=""
  [ -n "$MARS_VER" ] && MARS_FLAG="--mars_hw_rev=$MARS_VER"
