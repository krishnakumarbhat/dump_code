#!/bin/bash
# ============================================================================
#  Gen8 iND13400 - Build & Test Launcher (Bash version)
#  Runs bazelisk builds via Git Bash / WSL2 to bypass Windows 32K cmd limit.
#  Usage: bash STEP2_BUILD_OUTPUT_FILES.sh
# ============================================================================

set -e

# Navigate to repo root (three levels up from tools/python/testing_framework)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR/../../.."
REPO_ROOT="$(pwd)"
echo ""
echo "  Repo Root: $REPO_ROOT"
echo ""

# Enable long paths in Git to avoid "Filename too long" errors
git config --global core.longpaths true 2>/dev/null || true

# --- Credential Setup: Ensure .netrc exists for JFrog/Bazel authentication ---
if [ ! -f "$HOME/.netrc" ]; then
  # Running in WSL - try to copy .netrc from Windows user profile
  WIN_USER=$(cmd.exe /c "echo %USERNAME%" 2>/dev/null | tr -d '\r' || true)
  if [ -z "$WIN_USER" ]; then
    # Fallback: scan /mnt/c/Users for .netrc
    for d in /mnt/c/Users/*/; do
      if [ -f "${d}.netrc" ] && [ "$(basename "$d")" != "Public" ] && [ "$(basename "$d")" != "Default" ]; then
        cp "${d}.netrc" "$HOME/.netrc"
        chmod 600 "$HOME/.netrc"
        echo "  [INFO] Copied .netrc from ${d} to WSL home"
        break
      fi
    done
  elif [ -f "/mnt/c/Users/$WIN_USER/.netrc" ]; then
    cp "/mnt/c/Users/$WIN_USER/.netrc" "$HOME/.netrc"
    chmod 600 "$HOME/.netrc"
    echo "  [INFO] Copied .netrc from Windows user ($WIN_USER) to WSL home"
  fi
  if [ ! -f "$HOME/.netrc" ]; then
    echo "  [WARNING] ~/.netrc not found! Run repo_init.py on Windows first."
    echo "            Builds may fail with 401 authentication errors."
  fi
fi

# --- WSL/Linux user.bazelrc: Disable remote cache & BES (no API key locally) ---
# Also fix Windows-specific paths and workspace_status_command CRLF issues
if [[ "$OSTYPE" == "linux-gnu"* ]]; then
  # Fix CRLF line endings on all .sh scripts used by the build (Windows line endings break bash)
  find "$REPO_ROOT/software/common/versions/linkstamp" -name "*.sh" -exec sed -i 's/\r$//' {} \; -exec chmod +x {} \;
  find "$REPO_ROOT/tools/bazel/scripts" -name "*.sh" -exec sed -i 's/\r$//' {} \; -exec chmod +x {} \;
  # Fix awa.sh if present
  if [ -f "$REPO_ROOT/awa.sh" ]; then
    sed -i 's/\r$//' "$REPO_ROOT/awa.sh"
    chmod +x "$REPO_ROOT/awa.sh"
  fi

  # Generate a Linux-appropriate user.bazelrc if not present or is a Windows one
  if [ ! -f "$REPO_ROOT/user.bazelrc" ] || grep -q "C:/" "$REPO_ROOT/user.bazelrc" 2>/dev/null; then
    # Save Windows version as backup if it exists
    if [ -f "$REPO_ROOT/user.bazelrc" ] && grep -q "C:/" "$REPO_ROOT/user.bazelrc" 2>/dev/null; then
      cp "$REPO_ROOT/user.bazelrc" "$REPO_ROOT/user.bazelrc.win_backup"
    fi

    cat >"$REPO_ROOT/user.bazelrc" <<'EOF'
# =============================================================================
# WSL/Linux local user.bazelrc (auto-generated by STEP2_BUILD_OUTPUT_FILES.sh)
# =============================================================================

# Disable remote cache (no ARB API key available locally)
build --remote_cache=

# Disable Build Event Service (no API key)
build --bes_backend=
build --bes_results_url=

# Cache downloaded repos/archives so subsequent builds don't re-fetch
build --repository_cache=~/.cache/bazel_repo_cache

# Use most CPU cores
build --jobs=HOST_CPUS*.8

# Skip stamping for dev builds
build --nostamp
EOF
    echo "  [INFO] Generated Linux user.bazelrc (remote cache disabled)"
  else
    echo "  [INFO] Existing Linux user.bazelrc found - keeping it."
  fi

elif [[ "$OSTYPE" == "msys" || "$OSTYPE" == "cygwin" || "$OSTYPE" == "win32" ]]; then
  # Generate a Windows-appropriate user.bazelrc if not present
  if [ ! -f "$REPO_ROOT/user.bazelrc" ]; then
    cat >"$REPO_ROOT/user.bazelrc" <<'EOF'
# =============================================================================
# Windows local user.bazelrc (auto-generated by STEP2_BUILD_OUTPUT_FILES.sh)
# =============================================================================

# Short output base to avoid Windows long path failures (32K limit)
startup --output_base=C:/bzl

# Use 80% of CPU cores for parallel builds
common --jobs=HOST_CPUS*.8

# Only download top-level build outputs, not all intermediates
build --remote_download_toplevel

# Skip stamping for dev builds (prevents cache invalidation on every commit)
build --nostamp

# Disable Build Event Service for local dev (saves network I/O)
build --bes_backend=
build --bes_results_url=

# Local disk cache for faster rebuilds
build --disk_cache=C:/bzl_cache

# Use available RAM efficiently
build --local_resources=memory=HOST_RAM*.8

build --experimental_guard_against_concurrent_changes=false

# Use param files to avoid Windows 32K command-line limit (for xt-clang/BBE32)
build:windows --features=compiler_param_file

# Short temp dir for unit tests (avoids long path issues)
test:windows --@bazel_platform//quality/ut:tmp_dir=C:/tmp
EOF
    echo "  [INFO] Generated Windows user.bazelrc (short paths + disk cache)"
  else
    echo "  [INFO] Existing Windows user.bazelrc found - keeping it."
  fi
fi

# Detect environment and set bazelisk path
# On Windows/Git Bash/MSYS the repo-root "bazelisk" file is an ELF binary and cannot be
# exec'd there, so prefer "bazelisk.exe" first in that environment.
if [[ "$OSTYPE" == "msys" || "$OSTYPE" == "cygwin" || "$OSTYPE" == "win32" ]] && [ -f "./bazelisk.exe" ]; then
  BZL="./bazelisk.exe"
elif command -v bazelisk &>/dev/null; then
  BZL="bazelisk"
elif [ -f "./bazelisk" ]; then
  BZL="./bazelisk"
elif [ -f "./bazelisk.exe" ]; then
  BZL="./bazelisk.exe"
else
  echo "  [ERROR] bazelisk not found in PATH or repo root."
  exit 1
fi

# On Windows (Git Bash/MSYS2), use short output_base to reduce path lengths
if [[ "$OSTYPE" == "msys" || "$OSTYPE" == "cygwin" || "$OSTYPE" == "win32" ]]; then
  BZL="$BZL --output_base=C:/b"
  echo "  [INFO] Windows detected - using --output_base=C:/b"
fi
# On WSL2/Linux, no output_base override needed (no 32K limit)

# Colors for output (defined early so prerequisite checks can use them)
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m' # No Color

# --- Pre-build Prerequisite Checks ---
if [[ "$OSTYPE" == "linux-gnu"* ]]; then
  NEED_APT_UPDATE=true

  # Check mono (required for DvrlStreamTool.exe)
  if ! command -v mono &>/dev/null || ! mono --version &>/dev/null; then
    echo ""
    echo -e "  ${YELLOW}[INFO]${NC} 'mono' not found. Installing mono-complete..."
    sudo apt-get update -qq && NEED_APT_UPDATE=false
    sudo apt-get install -y -qq mono-complete
    if ! command -v mono &>/dev/null; then
      echo -e "  ${RED}[ERROR]${NC} Failed to install mono-complete. Please install manually:"
      echo "         sudo apt install -y mono-complete"
      exit 1
    fi
    echo -e "  ${GREEN}[OK]${NC} mono-complete installed successfully."
  elif ! dpkg -s libmono-system-windows-forms4.0-cil &>/dev/null 2>&1; then
    echo ""
    echo -e "  ${YELLOW}[INFO]${NC} mono found but missing System.Windows.Forms. Installing..."
    if $NEED_APT_UPDATE; then sudo apt-get update -qq && NEED_APT_UPDATE=false; fi
    sudo apt-get install -y -qq libmono-system-windows-forms4.0-cil
    echo -e "  ${GREEN}[OK]${NC} Mono Windows.Forms assembly installed."
  fi

  # Check libc6-i386 / 32-bit support (required for WindRiver Diab compiler)
  if ! dpkg -s libc6-i386 &>/dev/null 2>&1 && ! dpkg -s libc6:i386 &>/dev/null 2>&1; then
    echo ""
    echo -e "  ${YELLOW}[INFO]${NC} 32-bit libraries not found. Installing (required for WindRiver dcc)..."
    if $NEED_APT_UPDATE; then sudo apt-get update -qq && NEED_APT_UPDATE=false; fi
    sudo dpkg --add-architecture i386 2>/dev/null || true
    sudo apt-get update -qq
    sudo apt-get install -y -qq libc6:i386 libstdc++6:i386 zlib1g:i386
    echo -e "  ${GREEN}[OK]${NC} 32-bit libraries installed."
  fi
fi

