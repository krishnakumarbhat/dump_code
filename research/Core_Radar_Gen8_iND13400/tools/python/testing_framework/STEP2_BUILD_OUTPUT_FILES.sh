  ROT_FLAG=""
  [ -n "$ROT_VAL" ] && ROT_FLAG="--rot_gen=$ROT_VAL"
  echo ""

  # --- Step 7: Optional debug flags ---
  echo "  ====== Optional Debug / Feature Flags (y to enable, Enter to skip) ======"
  echo ""
  DBG_FLAGS=""

  echo "  --- Logging and Profiling ---"
  read -rp "  Enable ADC Logging?                [y/N]: " f1
  [[ "${f1,,}" == "y" ]] && DBG_FLAGS="$DBG_FLAGS --enable_adc_logging=True"

  read -rp "  Enable CDC Logging?                [y/N]: " f2
  [[ "${f2,,}" == "y" ]] && DBG_FLAGS="$DBG_FLAGS --enable_cdc=True"

  read -rp "  Enable Chirp Profiling?            [y/N]: " f3
  [[ "${f3,,}" == "y" ]] && DBG_FLAGS="$DBG_FLAGS --enable_chirp_profiling=True"

  read -rp "  Enable UART?                       [y/N]: " f4
  [[ "${f4,,}" == "y" ]] && DBG_FLAGS="$DBG_FLAGS --enable_uart=True"

  read -rp "  Enable Stream Re-generation?       [y/N]: " f5
  [[ "${f5,,}" == "y" ]] && DBG_FLAGS="$DBG_FLAGS --enable_stream_generation=True"

  echo ""
  echo "  --- Safety / Monitor Disable ---"
  read -rp "  Disable Stack Monitor (R52)?       [y/N]: " f6
  [[ "${f6,,}" == "y" ]] && DBG_FLAGS="$DBG_FLAGS --disable_stack_monitor_r52=true"

  read -rp "  Disable Program Flow Monitor?      [y/N]: " f7
  [[ "${f7,,}" == "y" ]] && DBG_FLAGS="$DBG_FLAGS --disable_pfm=true"

  read -rp "  Disable Internal Watchdog?         [y/N]: " f8
