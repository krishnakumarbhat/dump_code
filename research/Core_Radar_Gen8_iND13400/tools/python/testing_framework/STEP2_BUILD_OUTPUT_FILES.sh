  run_build "Custom Build ($CONFIG)" "//:gen8 $CONFIG $VEH_COM $TRACKER $BOARD_FLAG $MARS_FLAG $BBE_FLAG $ROT_FLAG $DBG_FLAGS $RAW_FLAGS $EXTRA_FLAGS"
}

# ============================================================================
#  MAIN MENU LOOP
# ============================================================================

main_menu() {
  while true; do
    print_menu
    echo ""
    # Flush any buffered terminal escape sequences before reading input
    read -r -t 0.1 -n 1000 _ 2>/dev/null || true
    read -rp "Select an option [0-18]: " choice

    case "$choice" in
      0) exit 0 ;;
      1)
        echo ""
        echo "  [CLEAN] Running bazelisk clean ..."
        $BZL clean
        echo "  [CLEAN] Done."
        post_build_menu
        ;;
      2)
        echo ""
        echo "  [EXPUNGE] Running bazelisk clean --expunge ..."
        $BZL clean --expunge
        echo "  [EXPUNGE] Done. All cached build outputs removed."
        post_build_menu
        ;;
      3)
        collect_optional_flags
        run_build "Satellite-CAN FLR8" "//:gen8 --config=flr8 $EXTRA_FLAGS"
        ;;
      4)
        collect_optional_flags
        run_build "Satellite-CAN SRR8P" "//:gen8 --config=srr8p $EXTRA_FLAGS"
        ;;
      5)
        collect_optional_flags
        run_build "Satellite-SomeIP FLR8" "//:gen8 --config=flr8 --veh_com=someip $EXTRA_FLAGS"
        ;;
      6)
        collect_optional_flags
        run_build "Satellite-SomeIP SRR8P" "//:gen8 --config=srr8p --veh_com=someip $EXTRA_FLAGS"
        ;;
      7)
        collect_optional_flags
        run_build "Standalone-FLR8" "//:gen8 --config=flr8 --veh_com=none --tracker_variant=platform_flr8_standalone $EXTRA_FLAGS"
        ;;
      8)
        collect_optional_flags
        run_build "Standalone-SRR8P" "//:gen8 --config=srr8p --veh_com=none --tracker_variant=platform_srr8p_standalone $EXTRA_FLAGS"
        ;;
      9)
        collect_optional_flags
        run_build "AL-SRR8P (Ashok Leyland CAN + Tracker)" "//:gen8 --config=srr8p --veh_com=al_can_standalone --tracker_variant=AL --enable_features=true $EXTRA_FLAGS"
        ;;
      10)
        run_cmd "TEST" "test //:all_unit_tests --test_output=all"
        ;;
      11)
        run_cmd "TEST" "test //:tests_bbe --test_output=all"
        ;;
      12)
        run_cmd "COVERAGE" "test //coverage:report"
        ;;
      13)
        run_cmd "COVERITY" "build //software/r52:windriver_r52_cov --config=flr8"
        ;;
      14)
        run_cmd "COVERITY" "build //software/r52:windriver_r52_cov --config=srr8p"
        ;;
      15)
        run_cmd "COVERITY" "build //software/bbe32:xtensa_bbe32_cov --config=flr8"
        ;;
      16)
        run_cmd "COVERITY" "build //software/bbe32:xtensa_bbe32_cov --config=srr8p"
        ;;
      17)
        run_cmd "COMPILEDB" "run //:compiledb"
        ;;
      18)
        collect_optional_flags
        custom_build
        ;;
      *)
        echo ""
        echo "  [ERROR] Invalid selection: \"$choice\""
        echo ""
        ;;
    esac
  done
}

# Cleanup: Restore Windows user.bazelrc on exit (if we backed it up)
cleanup() {
  if [ -f "$REPO_ROOT/user.bazelrc.win_backup" ]; then
    mv "$REPO_ROOT/user.bazelrc.win_backup" "$REPO_ROOT/user.bazelrc"
  fi
}
trap cleanup EXIT

# Start
main_menu
