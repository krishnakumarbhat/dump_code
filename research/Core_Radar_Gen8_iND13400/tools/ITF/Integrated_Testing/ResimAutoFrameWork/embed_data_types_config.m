                            'data_type', 'uint16', ...
                            'scale_by_type', false, ...
                            'description', 'Angle bin index for each detection');

   % Range-Doppler amplitude - uint16, scaled
   config('rdop_amp') = struct( ...
                               'data_type', 'uint16', ...
                               'scale_by_type', true, ...
                               'description', 'Range-Doppler amplitude for each detection');

   % Range bin estimate - uint32, not scaled
   config('rbinest') = struct( ...
                              'data_type', 'int32', ...
                              'scale_by_type', false, ...
                              'description', 'Fine range bin estimate');

   % Doppler bin estimate - uint32, not scaled
   config('dbinest') = struct( ...
                              'data_type', 'int32', ...
                              'scale_by_type', false, ...
                              'description', 'Fine doppler bin estimate');

   % Angle bin estimate - uint32, not scaled
