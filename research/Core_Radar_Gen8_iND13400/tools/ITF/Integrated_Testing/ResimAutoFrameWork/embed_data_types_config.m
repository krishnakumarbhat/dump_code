                                            'description', 'Bandwidth-dependent sensitivity threshold');

   % HVC Threshold - uint32, scaled
   config('HVC_Threshold') = struct( ...
                                    'data_type', 'uint32', ...
                                    'scale_by_type', true, ...
                                    'description', 'Bandwidth-dependent HVC threshold');

