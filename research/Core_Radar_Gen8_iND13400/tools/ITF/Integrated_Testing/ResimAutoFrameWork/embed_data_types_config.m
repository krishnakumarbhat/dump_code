                                      'description', 'Minimum chirp scaling factor');

   % Debug: IDM statistics - uint16, NOT be scaled (debug signal)
   config('idm_stats') = struct( ...
                                'data_type', 'uint16', ...
                                'scale_by_type', false, ...
                                'description', 'IDM (Interference Detection) statistics (debug)');

   %% ====================================================================
