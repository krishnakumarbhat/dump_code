   % Debug: NCI block exponent - uint16, should NOT be scaled
   config('nci_bexp') = struct( ...
                               'data_type', 'uint16', ...
                               'scale_by_type', false, ...
                               'description', 'NCI block exponent (debug signal)');

   %% ====================================================================
   %  Second_Pass (Extended Tracking Filter) Module
   %  From: t32_SPdata_collect.m
   %  ====================================================================

   % Range - int32, not scaled
   config('range') = struct( ...
                            'data_type', 'int32', ...
                            'scale_by_type', false, ...
                            'description', 'Range estimate after second pass');

   % Range rate (velocity) - int32, not scaled
   config('range_rate') = struct( ...
                                 'data_type', 'int32', ...
                                 'scale_by_type', false, ...
                                 'description', 'Range rate (velocity) estimate');

   % SNR - int32, not scaled
   config('snr') = struct( ...
                          'data_type', 'int32', ...
                          'scale_by_type', false, ...
                          'description', 'Signal-to-Noise Ratio');

   % Second pass fail flag - uint8, should NOT be scaled (it's a flag)
   config('sp_fail_flag') = struct( ...
                                   'data_type', 'uint8', ...
                                   'scale_by_type', false, ...
                                   'description', 'Second pass failure flag');

