%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% embed_data_types_config
%
% Centralized configuration for embedded output data types and scaling
% control. This configuration is used by measure_error_calc() to determine:
%   1. Expected data type for each embedded output field
%   2. Whether scaling by data type should be applied for that field
%
% Configuration Structure:
%   config = containers.Map with:
%     Key: Field name (string) - matches var_data{:, 1}
%     Value: struct with fields:
%       - data_type: MATLAB class name ('uint8', 'uint16', 'uint32', 'uint64',
%                    'int8', 'int16', 'int32', 'int64', 'single', 'double')
%       - scale_by_type: boolean (true = apply scaling, false = no scaling)
%       - description: Optional description of the field
%
% Usage Examples:
%   cfg = embed_data_types_config();
%   if cfg.isKey('detection_range')
%       info = cfg('detection_range');
%       fprintf('Type: %s, Scale: %d\n', info.data_type, info.scale_by_type);
%   end
%
% Notes:
%   - Integer types (uint*/int*) with scale_by_type=true will be scaled by 2^bitwidth
%   - Float types (single/double) are not scaled even if scale_by_type=true
%   - Fields not in this config will fall back to class() introspection
%   - Counter/index fields should have scale_by_type=false to preserve raw values
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

function config = embed_data_types_config()
