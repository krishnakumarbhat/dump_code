                                      'scale_by_type', true, ...
                                      'description', 'Decompressed doppler FFT data');

   % Scaled NCI - double, not scaled
   config('scaled_nci') = struct( ...
                                 'data_type', 'double', ...
                                 'scale_by_type', false, ...
                                 'description', 'Scaled non-coherent integration data');

   % Range-Doppler average NCI - uint16, scaled
   config('rdop_avg_NCI') = struct( ...
                                   'data_type', 'uint16', ...
                                   'scale_by_type', true, ...
                                   'description', 'Range-Doppler averaged NCI data');

   %% ====================================================================
   %  Angle_Finding Module
   %  From: t32_AFdata_collect.m
   %  ====================================================================

