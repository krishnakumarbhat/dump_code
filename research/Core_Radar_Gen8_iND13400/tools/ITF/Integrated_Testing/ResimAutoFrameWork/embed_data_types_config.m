                                 'data_type', 'int32', ...
                                 'scale_by_type', false, ...
                                 'description', 'Number of detections after angle finding');

   % Range - single, scaled
   config('ran') = struct( ...
                          'data_type', 'single', ...
                          'scale_by_type', true, ...
                          'description', 'Range estimate from angle finding');

   % Velocity - single, scaled
   config('vel') = struct( ...
                          'data_type', 'single', ...
                          'scale_by_type', true, ...
                          'description', 'Velocity estimate from angle finding');

   % Power - single, scaled
   config('pow') = struct( ...
                          'data_type', 'single', ...
                          'scale_by_type', true, ...
                          'description', 'Detection power from angle finding');

   % Theta (azimuth angle) - single, scaled
   config('theta') = struct( ...
                            'data_type', 'single', ...
                            'scale_by_type', true, ...
                            'description', 'Azimuth angle (theta) in radians');

   % Phi (elevation angle) - single, scaled
   config('phi') = struct( ...
                          'data_type', 'single', ...
                          'scale_by_type', true, ...
                          'description', 'Elevation angle (phi) in radians');

   % Azimuth confidence - int8, should NOT be scaled (confidence metric/flag)
   config('az_conf') = struct( ...
                              'data_type', 'int8', ...
                              'scale_by_type', false, ...
                              'description', 'Azimuth angle confidence metric');

