%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Name: CreateSubReport
%   Creates the beginning of a test case report HTML page.
%
% Inputs:
%   radar_name, test_case_num, test_case_cnt, test_name
%   path_to_report_directory, CFAR_flag, comparison_type_flag
%   workbook, USC_version, BB_version
%   mex_embed_mode  (optional, default false)
%     true  => Mex-vs-Embed column layout (2-column comparison)
%     false => standard layout (3-way or 2-way Algo/Embed)
%   spec_mex_mode  (optional, default false)
%     true  => Spec-vs-Mex column layout (shows Spec instead of Embed)
%     false => standard layout
%
% Return Variables:
%   HTML_string: HTML content to write to file
%   filename:    full path of the output HTML file
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

function [HTML_string, filename] = CreateSubReport(radar_name, test_case_num, test_case_cnt, test_name, path_to_report_directory, CFAR_flag, comparison_type_flag, workbook, USC_version, BB_version, mex_embed_mode, spec_mex_mode)
   if nargin < 11
      mex_embed_mode = false;
   end
   if nargin < 12
      spec_mex_mode = false;
   end
   global test_case_name
   global test_case
   file = [path_to_report_directory, '\Reports\Testcases\Testcase_', num2str(test_case_num), '.html'];

   dt = datetime('now');
   date = char(dt, 'dd-MMM-yyyy');
   time = char(dt, 'HH:mm:ss');

   filename = file;
   HTML_string = [];
   if ~(ischar(test_case_name) || isstring(test_case_name)) || isempty(test_case_name)
      test_case_name = test_name;
   end
   test_case_name = char(test_case_name);
   test_case_number = '';
   test_case_string = strsplit(test_case_name, '_');
   if numel(test_case_string) >= 2
      test_case_number = test_case_string{2};
   end
   if isempty(test_case_number)
      test_case_number = '';
   end
   if strcmp(test_case_number, '001')
      test_case = 'Single target case';
   elseif strcmp(test_case_number, '002')
      test_case = 'Two targets in different range bins';
   elseif strcmp(test_case_number, '003')
      test_case = 'DC bias removal case';
   elseif strcmp(test_case_number, '004')
      test_case = 'Two targets one of which is below BPM residue level';
   elseif strcmp(test_case_number, '005')
      test_case = 'Low SNR target case';
   elseif strcmp(test_case_number, '006')
      test_case = 'Zero Target Case-Noise only (33dB noise floor)';
   elseif strcmp(test_case_number, '007')
      test_case = 'Low Noise Floor (8dB NF)';
   elseif strcmp(test_case_number, '008')
      test_case = 'High Noise Floor (85dB NF)';
   elseif strcmp(test_case_number, '009')
      test_case = 'Targets at near and far ranges';
   elseif strcmp(test_case_number, '010')
      test_case = 'Case with number of targets exceeding over max_detects';
   elseif strcmp(test_case_number, '011')
      test_case = 'CDC log for single target case';
   elseif strcmp(test_case_number, '012')
      test_case = 'CDC log for test case having CDC maximum limit';
   elseif strcmp(test_case_number, '013')
      test_case = 'Detection passes 1st pass and fails 2nd Pass';
   elseif strcmp(test_case_number, '014')
      test_case = 'Test case for minimum RCS';
   elseif strcmp(test_case_number, '015')
      test_case = 'Test case for maximum RCS';
   elseif strcmp(test_case_number, '016')
      test_case = 'Verify Azimuth Angle';
   elseif strcmp(test_case_number, '017')
      test_case = 'Test case for Superres';
   elseif strcmp(test_case_number, '018')
      test_case = 'ADC Data verification';
   elseif strcmp(test_case_number, '019')
      test_case = 'Test case for Range and Doppler';
   elseif strcmp(test_case_number, '020')
      test_case = 'Threshold Check';
   elseif strcmp(test_case_number, '021')
      test_case = 'Amplitude&Azimuth Verification';
   elseif strcmp(test_case_number, '022')
      test_case = 'Beam vector Phase Linearity check with Sweep test';
   elseif strcmp(test_case_number, '023')
      test_case = 'ZDB Threshold check';
   elseif strcmp(test_case_number, '024')
      test_case = 'Boundary Range Bin';
   elseif strcmp(test_case_number, '025')
      test_case = 'Boundary Doppler Bin';
   else
      test_case = 'test case not found';
   end

   % Generate Test Management Report Section
   HTML_string = [HTML_string ...
                  '<head><title>Testcase&nbsp;', num2str(test_case_num), '</title></head>', ...
                  '<div align="middle"><img src="https://www.underconsideration.com/brandnew/archives/aptiv_logo.png"alt="Aptiv Logo" style="width:342px;height:48px;"></div>\n', ...
                  '<table border="0" width="100%%" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr bgcolor="#ce380a">\n', ...
                  '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Table&nbsp;Of&nbsp;Contents</strong></td>\n', ...
                  '</tr>\n', ...
                  '<tr>\n', ...
                  '<td>\n', ...
                  '<table border="0" width="100%%" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td>\n', ...
                  '<ul>\n', ...
                  '<li><a href="#section1">Configuration&nbsp;Data</a>\n', ...
                  '</li><li><a href="#section2">Overall&nbsp;Results</a></li>\n', ...
                  '<li><a href="#section3">Testcase&nbsp;', num2str(test_case_num), '</a></li>\n', ...
                  '<li><a href="../Testcase_Summary.html">Testcase Summary</a></li>'...
                  '</ul>\n', ...
                  '</td>\n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n', ...
                  '</td>\n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n'];

   % Test Management Report Section 1
   HTML_string = [HTML_string ...
                  '<tbody>\n', ...
                  '<tr>\n', ...
                  '<td>\n', ...
                  '<a name="section1"></a>&nbsp;</td>\n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n', ...
                  '<table border="0" width="100%%" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr bgcolor="#ce380a">\n', ...
                  '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Configuration&nbsp;Data</strong></td>\n', ...
                  '</tr>\n', ...
                  '<tr>\n', ...
                  '<td>\n', ...
                  '<table border="0" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr>\n', ...
                  '<td colspan="2"><strong>This&nbsp;report&nbsp;includes&nbsp;data&nbsp;for:</strong></td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Test&nbsp;Name:</strong></td>\n', ...
                  '<td align="center">', test_name, '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Unit:</strong></td>\n', ...
                  '<td align="center">', radar_name, '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Workbook:&nbsp;</strong></td>\n', ...
                  '<td align="center">', num2str(workbook), '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>USC:&nbsp;</strong></td>\n', ...
                  '<td align="center">', num2str(USC_version), '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>BB version:&nbsp;</strong></td>\n', ...
                  '<td align="center">', num2str(BB_version), '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Date&nbsp;of&nbsp;Test:</strong></td>\n', ...
                  '<td align="center">', date, '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Time&nbsp;of&nbsp;Test:</strong></td>\n', ...
                  '<td align="center">', time, '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Test&nbsp;ID:&nbsp;</strong></td>\n', ...
                  '<td align="center">RCT_&nbsp;', test_case_number, '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Test&nbsp;case:&nbsp;</strong></td>\n', ...
                  '<td align="center">', test_case, '</td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Matlab&nbsp;Execution&nbsp;Time:</strong></td>\n', ...
                  'Execution_Time                                                            \n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Embedded&nbsp;Execution&nbsp;Time:</strong></td>\n', ...
                  'Embed_Time                                                            \n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n', ...
                  '</td>\n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n'];

   % Test Management Report Section 2
   HTML_string = [HTML_string ...
                  '<table>\n', ...
                  '<tbody>\n', ...
                  '<tr>\n', ...
                  '<td><a name="section2"></a>&nbsp;</td>\n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n', ...
                  '<table style="font-family: Arial; font-size: 10pt; color: #ffffff;" border="0" width="100%%" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr bgcolor="#ce380a">\n', ...
                  '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Overall&nbsp;Results</strong></span></td>\n', ...
                  '</tr>\n', ...
                  '<tr>\n', ...
                  '<td align="left">\n', ...
                  '<table style="font-family: Times New Roman; font-size: 12pt; color: #000000;" border="0" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr bgcolor="#CCD8EE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Category</strong></td>\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Results</strong></td>\n', ...
                  '</tr>\n', ...
                  '<tr bgcolor="#EEEEEE">\n', ...
                  '<td><strong>Testcase&nbsp;Pass/Fail:</strong></td>\n', ...
                  'Pass_Fail                                                                 \n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n', ...
                  '</td>\n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n', ...
                  '<tr bgcolor="#ffffff">\n', ...
                  '<td>\n'];
   if CFAR_flag
      HTML_string = [HTML_string '&nbsp;&nbsp;<a align="left" style="font-family: Arial; font-size: 8pt;" href="../Testcase_Summary.html">Summary</a>&nbsp;&nbsp;\n'];

   else
      if test_case_num == 1 && test_case_cnt ~= 1
         HTML_string = [HTML_string '&nbsp;&nbsp;<a align="left" style="font-family: Arial; font-size: 8pt;" href="../Testcase_Summary.html">Summary</a>&nbsp;&nbsp;\n'];
      end
      if test_case_num ~= 1
         HTML_string = [HTML_string '&nbsp;&nbsp;<a align="left" style="font-family: Arial; font-size: 8pt;" href="./Testcase_', num2str(test_case_num - 1), '.html">Previous</a>&nbsp;&nbsp;\n'];
      end
      if test_case_num ~= test_case_cnt
         HTML_string = [HTML_string '&nbsp;&nbsp;<a align="right" style="font-family: Arial; font-size: 8pt;" href="./Testcase_', num2str(test_case_num + 1), '.html">Next</a></td>\n'];
      end
      if test_case_num == test_case_cnt
         HTML_string = [HTML_string '&nbsp;&nbsp;<a align="right" style="font-family: Arial; font-size: 8pt;" href="../Testcase_Summary.html">Summary</a></td>\n'];
      end
   end

   % Section 3 — column headers depend on mode
   sec3_prefix = [HTML_string, ...
                  '</tr>\n', ...
                  '<table>\n', ...
                  '<tbody>\n', ...
                  '<tr>\n', ...
                  '<td><a name="section3"></a>&nbsp;</td>\n', ...
                  '</tr>\n', ...
                  '</tbody>\n', ...
                  '</table>\n', ...
                  '<table border="0" width="100%%" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr bgcolor="#ce380a">\n', ...
                  '<td></div>\n', ...
                  '<span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>&nbsp;Testcase&nbsp;', num2str(test_case_num), '</strong></td>\n', ...
                  '</tr>\n', ...
                  '<tr>\n', ...
                  '<td>\n', ...
                  '<table border="0" cellpadding="2">\n', ...
                  '<tbody>\n', ...
                  '<tr bgcolor="#CCD8EE">\n', ...
                  '<td bgcolor="#CCD8EE"><strong>Test Variable</strong></td>\n'];

   if comparison_type_flag == 1
      if spec_mex_mode
         % Two-column: MEX Output vs Spec Output (Spec-vs-Mex mode)
         HTML_string = [sec3_prefix ...
                        '<td bgcolor="#CCD8EE"><strong>MEX_Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Spec_Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Accepted Range&nbsp;&nbsp;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>(MEX_Output - Spec_Output) &#916;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>MEX_Output Vs. Spec_Output P/F</strong></td>\n', ...
                        '</tr>\n'];
      elseif mex_embed_mode
         % Two-column: MEX Output vs Embedded Output
         HTML_string = [sec3_prefix ...
                        '<td bgcolor="#CCD8EE"><strong>MEX_Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Embed_Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Accepted Range&nbsp;&nbsp;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>(MEX_Output - Embed_Output) &#916;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>MEX_Output Vs. Embed_Output P/F</strong></td>\n', ...
                        '</tr>\n'];
      else
         % Three-column: Executable Spec vs MEX vs Embedded
         HTML_string = [sec3_prefix ...
                        '<td bgcolor="#CCD8EE"><strong>Executable Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>MEX Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Embedded Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Accepted Range&nbsp;&nbsp;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Spec - Mex &#916;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Spec v. Mex P/F</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Spec - Embed &#916;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Spec v. Embed P/F</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Mex - Embed &#916;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Mex v. Embed P/F</strong></td>\n', ...
                        '</tr>\n'];
      end
   else
      if mex_embed_mode
         % Legacy two-way mex-embed: Algorithm Output only
         HTML_string = [sec3_prefix ...
                        '<td bgcolor="#CCD8EE"><strong>Algorithm Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Accepted Range&nbsp;&nbsp;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Pass/Fail</strong></td>\n', ...
                        '</tr>\n'];
      else
         % Legacy two-way: Algorithm Output vs Embedded
         HTML_string = [sec3_prefix ...
                        '<td bgcolor="#CCD8EE"><strong>Algorithm Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Embedded Output</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Accepted Range&nbsp;&nbsp;</strong></td>\n', ...
                        '<td bgcolor="#CCD8EE"><strong>Pass/Fail</strong></td>\n', ...
                        '</tr>\n'];
      end
   end
end
