%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% Name: getConslReport
%   This function generates the consolidated HTML report for all the test
%   cases run through RunTest_Suite_it.m
%
% Return Variables: N/A
%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function getConslReport(SMC, USC)

   global sensor_type
   global usc_ver
   global sw_id

   % Get date and time info
   time_info = datestr(now);
   time_info = strsplit(time_info, ' ');
   date = char(time_info(1));
   time = char(time_info(2));

   % Configuration data information
   SMC_Version = SMC.Workbook.Workbook_Version.VALUE;
   USC_Version = usc_ver;
   Release_Version = sw_id;
   Variant = sensor_type;

   % % Get folder path location and extract the folder information
   selpath = '.\Reports';
   d =  dir(selpath);
   dfolders = d([d(:).isdir]);
   test_case_info = dfolders(~ismember({dfolders(:).name}, {'.', '..'}));

   % Create header for overall summary  and configuration info(HTML format)
   summary_string = ['<head><title>Testcase&nbsp;Summary</title></head>', ...
                     '<div align="middle"><img src="https://www.underconsideration.com/brandnew/archives/aptiv_logo.png"alt="Aptiv Logo" style="width:342px;height:48px;"></div>\n', ...
                     '<div align="left"><span style="font-family: Arial; font-size: 16pt; color: #000000;"><strong>Overall Testcase Results</strong></div>\n', ...
                     '<table border="0" width="100%%" cellpadding="2">\n', ...
                     '<tbody>\n', ...
                     '<tr bgcolor="#ce380a">\n', ...
                     '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Table&nbsp;Of&nbsp;Contents</strong></td>\n', ...
                     '</tr>\n', ...
                     '<tr>\n', ...
                     '<td>\n', ...
                     '<table border="0" width="100%%" cellpadding="2">\n', ...
                     '<tbody>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td>\n', ...
                     '<ul>\n', ...
                     '<li><a href="#section1">Configuration&nbsp;Data</a>\n', ...
                     '<li><a href="#section3">Testcase&nbsp;Results</a></li>\n', ...
                     '</ul>\n', ...
                     '</td>\n', ...
                     '</tr>\n', ...
                     '</tbody>\n', ...
                     '</table>\n', ...
                     '</td>\n', ...
                     '</tr>\n', ...
                     '</tbody>\n', ...
                     '</table>\n'....
                     '<tbody>\n', ...
                     '<tr>\n', ...
                     '<td>\n', ...
                     '<a name="section1"></a>&nbsp;</td>\n', ...
                     '</tr>\n', ...
                     '</tbody>\n', ...
                     '</table>\n', ...
                     '<table border="0" width="100%%" cellpadding="2">\n', ...
                     '<tbody>\n', ...
                     '<tr bgcolor="#ce380a">\n', ...
                     '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Configuration&nbsp;Data</strong></td>\n', ...
                     '</tr>\n', ...
                     '<tr>\n', ...
                     '<td>\n', ...
                     '<table border="0" cellpadding="2">\n', ...
                     '<tbody>\n', ...
                     '<tr>\n', ...
                     '<td colspan="2"><strong>This&nbsp;report&nbsp;includes&nbsp;data&nbsp;for:</strong></td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>Test&nbsp;Name:</strong></td>\n', ...
                     '<td align="center">', ' Integration Test', '</td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>Variant:</strong></td>\n', ...
                     '<td align="center">', Variant, '</td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>Release Version:</strong></td>\n', ...
                     '<td align="center">', Release_Version, '</td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>SMC&nbsp;Version:</strong></td>\n', ...
                     '<td align="center">', SMC_Version, '</td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>USC&nbsp;Version:</strong></td>\n', ...
                     '<td align="center">', USC_Version, '</td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>Number of Testcases:&nbsp;</strong></td>\n', ...
                     '<td align="center">', num2str(length(test_case_info)), '</td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>Date&nbsp;of&nbsp;Test:</strong></td>\n', ...
                     '<td align="center">', date, '</td>\n', ...
                     '</tr>\n', ...
                     '<tr bgcolor="#EEEEEE">\n', ...
                     '<td bgcolor="#CCD8EE"><strong>Time&nbsp;of&nbsp;Test:</strong></td>\n', ...
                     '<td align="center">', time, '</td>\n', ...
                     '</tr>\n', ...
                     '</tr>\n', ...
                     '</tbody>\n', ...
                     '</table>\n', ...
                     '</td>\n', ...
                     '</tr>\n', ...
                     '</tbody>\n', ...
                     '</table>\n'...
                     '<table>\n', ...
                     '<tbody>\n', ...
                     '<tr>\n', ...
                     '<td><a name="section2"></a>&nbsp;</td>\n', ...
                     '</tr>\n', ...
                     '</tbody>\n', ...
                     '</table>\n', ...
                     '<table border="0" width="100%%" cellpadding="2">\n', ...
                     '<tbody>\n', ...
                     '<tr bgcolor="#ce380a">\n', ...
                     '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Testcase Results</strong></td>\n', ...
                     '</tr>\n', ...
                     '<tr>\n', ...
                     '<td>\n', ...
                     '<table border="0" cellpadding="2">\n', ...
                     '<tbody>\n', ...
                     '<tr bgcolor="#CCD8EE"><td bgcolor="#CCD8EE"><strong>Testcase&nbsp;No.&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</strong></td>\n', ...
                     '<td bgcolor="#CCD8EE"><strong>Testcase Pass/Fail:&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</strong></td>\n', ...
                     '</tr>'];

   % Loop over each test case
   for i = 1:length(test_case_info)

      % Html summary update for each test case
      summary_string = [summary_string ...
                        '<tr>\n', ...
                        '<td bgcolor="#CCD8EE">' test_case_info(i).name '</td>'];

      filename = strcat(selpath, '\', test_case_info(i).name, '\Integration_Test_Summary.html');
      if ~(isfile(filename))
         str = [];
      else
         str = extractFileText(filename);
      end
      if ~isempty(str)
         % Locate the "Testcase Pass/Fail:" row and parse the actual
         % "<pass> / <total>" counts written by HTML_Insert.m, which uses
         % a "%8d&nbsp;/%8d" format (variable-width, space-padded).
         % Using a regex anchored on the literal token instead of fixed
         % character offsets avoids misreading digits when pass/total
         % counts have differing widths.
         tokens = regexp(str, 'Testcase Pass/Fail:.*?(\d+)\s*&nbsp;/\s*(\d+)', 'tokens', 'once');

         if isempty(tokens)
            % Fallback in case &nbsp; was decoded to a literal space by
            % extractFileText (no HTML entity present in the DOM text).
            tokens = regexp(str, 'Testcase Pass/Fail:.*?(\d+)\s*/\s*(\d+)', 'tokens', 'once');
         end

         if isempty(tokens)
            warning('[Suite##Warn] Could not parse Testcase Pass/Fail counts for %s. Marking as ERROR.', test_case_info(i).name);
            Testcasepassed = NaN;
            Total_testcases = NaN;
         else
            Testcasepassed = str2double(tokens{1});
            Total_testcases = str2double(tokens{2});
         end

         if isnan(Testcasepassed) || isnan(Total_testcases) || Total_testcases == 0
            result = "ERROR";
         else
            percent = (Testcasepassed / Total_testcases) * 100;
            % Aligned with the 98% threshold used in DataCompare.m's
            % finalize_summary() so the consolidated report's PASS/FAIL
            % matches the criteria used to generate individual reports.
            if percent >= 98
               result = "PASS";
            else
               result = "FAIL";
            end
         end

         % Append result cell with color & link
         if strcmp(result, "PASS")
            summary_string = [summary_string ...
                              '<td bgcolor=#CCFFCC><a href="./' test_case_info(i).name '/Integration_Test_Summary.html">PASS</a></td>'];
         elseif strcmp(result, "FAIL")
            summary_string = [summary_string ...
                              '<td bgcolor=#FF9292><a href="./' test_case_info(i).name '/Integration_Test_Summary.html">FAIL</a></td>'];
         else
            % result == "ERROR" (counts could not be parsed)
            summary_string = [summary_string ...
                              '<td bgcolor=#FF8080><a href="./' test_case_info(i).name '/Integration_Test_Summary.html">ERROR</a></td>'];
         end
      else
         summary_string = [summary_string ...
                           '<td bgcolor=#FF8080>ERROR</td>'];

      end
      summary_string = [summary_string ...
                        '<tr>'];
   end

   % Update html file
   summary_string = [summary_string, '</tbody>\n</table>\n</td>\n</tr>\n</tbody>\n</table>'];
   summary_string = strcat(summary_string, '');
   fid = fopen(strcat(selpath, '\Integration_Test_Summary_consolidated.html'), 'w+');
   fprintf(fid, summary_string);
   fclose(fid);
