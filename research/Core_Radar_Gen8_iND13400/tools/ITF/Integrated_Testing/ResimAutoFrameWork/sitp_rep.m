%% sitp_rep.m
% This function generates the Software Integration Test Report in HTML format
% Inputs:
%   tc_fail_cnt - Array containing the number of failed test cases
%   tot_report_cnt - Total number of test cases executed
%   testcase_dir_name - Name of the directory containing the test case
%   SMC - Structure containing SMC configuration data
%   sw_id - Software ID string
%   USC - Structure containing USC configuration data
%   itr - Current iteration number
% Outputs:
%   varargout
function varargout = sitp_rep(tc_fail_cnt, tot_report_cnt, testcase_dir_name, SMC, sw_id, USC, itr)

   global sensor_type
   global test_case
   global look_string

   global dir_size
   global call_count
   global sitp_summary_string
   global sitp_rep_first_call
   global test_case_result
   global sitp_color
   global str_label
   global sitp_error
   Test_ID = testcase_dir_name;
   test_case_result{1} = Test_ID;

   platform = SMC.Configuration.BB_Configuration.K_PLATFORM_VARIANT.VALUE; % radar_sw_config.K_Platform_Variant;

   % SMC_Version = radar_sw_config.const_params.version; %radar_sw_config.version;
   % USC_Version = USC.K_cal_revision_number;
   SW_ID = sw_id;
   dt = datetime('now');
   date = char(dt, 'dd-MMM-yyyy');
   time = char(dt, 'HH:mm:ss');

   if sitp_rep_first_call
      sitp_rep_first_call = 0;
      % Create header for overall summary
      sitp_summary_string = ['<head><title>Testcase&nbsp;Summary</title></head>', ...
                             '<div align="middle"><img src="https://www.underconsideration.com/brandnew/archives/aptiv_logo.png"alt="Aptiv Logo" style="width:342px;height:48px;"></div>\n', ...
                             '<div align="middle"><span style="font-family: Arial; font-size: 25pt; color: #000000;"><strong>Integration Test Report</strong></div>\n', ...
                             '<table border="0" width="100%%" cellpadding="2">\n', ...
                             '<tbody>\n', ...
                             '<tr bgcolor="#ce380a">\n', ...
                             '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Table&nbsp;Of&nbsp;Contents</strong></td>\n', ...
                             '</tr>\n', ...
                             '<tr>\n', ...
                             '<td>\n', ...
                             '<table border="0" width="100%%" cellpadding="2">\n', ...
                             '<tbody>\n', ...
                             '<tr bgcolor="#EEEEEE">\n', ...
                             '<td>\n', ...
                             '<ul>\n', ...
                             '<li><a href="#section1">Configuration&nbsp;Data</a></li>\n', ...
                             '<li><a href="#section2">Testcase&nbsp;Results</a></li>\n', ...
                             '</ul>\n', ...
                             '</td>\n', ...
                             '</tr>\n', ...
                             '</tbody>\n', ...
                             '</table>\n', ...
                             '</td>\n', ...
                             '</tr>\n', ...
                             '</tbody>\n', ...
                             '</table>\n'];

      % Test Management Report Section 1
      sitp_summary_string = [sitp_summary_string ...
                             '<tbody>\n', ...
                             '<tr>\n', ...
                             '<td>\n', ...
                             '<a name="section1"></a>&nbsp;</td>\n', ...
                             '</tr>\n', ...
                             '</tbody>\n', ...
                             '</table>\n', ...
                             '<table border="0" width="100%%" cellpadding="2">\n', ...
                             '<tbody>\n', ...
                             '<tr bgcolor="#ce380a">\n', ...
                             '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Configuration&nbsp;Data</strong></td>\n', ...
                             '</tr>\n', ...
                             '<tr>\n', ...
                             '<td>\n', ...
                             '<table border="0" cellpadding="2">\n', ...
                             '<tbody>\n', ...
                             '<tr>\n', ...
                             '<td colspan="2"><strong>This&nbsp;report&nbsp;includes&nbsp;data&nbsp;for:</strong></td>\n', ...
                             '</tr>\n', ...
                             '<tr bgcolor="#EEEEEE">\n', ...
                             '<td bgcolor="#CCD8EE"><strong>Test&nbsp;Name:</strong></td>\n', ...
                             '<td align="center">', ' Integration Test', '</td>\n', ...
                             '</tr>\n', ...
                             '<tr bgcolor="#EEEEEE">\n', ...
                             '<td bgcolor="#CCD8EE"><strong>Variant:</strong></td>\n', ...
                             '<td align="center">', sensor_type, '</td>\n', ...
                             '</tr>\n', ...
                             '<tr bgcolor="#EEEEEE">\n', ...
                             '<td bgcolor="#CCD8EE"><strong>Number of Testcases:&nbsp;</strong></td>\n', ...
                             '<td align="center">', num2str(dir_size), '</td>\n', ...
                             '</tr>\n', ...
                             '<tr bgcolor="#EEEEEE">\n', ...
                             '<td bgcolor="#CCD8EE"><strong>Date&nbsp;of&nbsp;Test:</strong></td>\n', ...
                             '<td align="center">', date, '</td>\n', ...
                             '</tr>\n', ...
                             '<tr bgcolor="#EEEEEE">\n', ...
                             '<td bgcolor="#CCD8EE"><strong>Time&nbsp;of&nbsp;Test:</strong></td>\n', ...
                             '<td align="center">', time, '</td>\n', ...
                             '</tr>\n', ...
                             '</tr>\n', ...
                             '</tbody>\n', ...
                             '</table>\n', ...
                             '</td>\n', ...
                             '</tr>\n', ...
                             '</tbody>\n', ...
                             '</table>\n'];
      sitp_summary_string = [sitp_summary_string ...
                             '<table>\n', ...
                             '<tbody>\n', ...
                             '<tr>\n', ...
                             '<td><a name="section2"></a>&nbsp;</td>\n', ...
                             '</tr>\n', ...
                             '</tbody>\n', ...
                             '</table>\n', ...
                             '<table border="0" width="100%%" cellpadding="2">\n', ...
                             '<tbody>\n', ...
                             '<tr bgcolor="#ce380a">\n', ...
                             '<td align="left"><span style="font-family: Arial; font-size: 14pt; color: #ffffff;"><strong>Testcase Results</strong></td>\n', ...
                             '</tr>\n', ...
                             '<tr>\n', ...
                             '<td>\n', ...
                             '<table border="0" cellpadding="2">\n', ...
                             '<tbody>\n', ...
                             '<tr bgcolor="#CCD8EE"><td bgcolor="#CCD8EE"><strong>Testcase&nbsp;No.&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</strong></td>\n', ...
                             '<td bgcolor="#CCD8EE"><strong>LRLL&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</strong></td>\n', ...
                             '<td bgcolor="#CCD8EE"><strong>LRML&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</strong></td>\n', ...
                             '<td bgcolor="#CCD8EE"><strong>MRLL&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</strong></td>\n', ...
                             '<td bgcolor="#CCD8EE"><strong>MRML&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;</strong></td>\n', ...
                             '</tr>\n'];
   end
   testcase_pass = 0;
   testcase_fail = 0;
   % for i = 1:(tot_report_cnt - 1)
   %     if (tc_fail_cnt(i) == 0)
   %         testcase_pass = testcase_pass + 1;
   %     else
   %         testcase_fail = testcase_fail + 1;
   %     end
   % end

   % if testcase_pass == tot_report_cnt - 1
   %     pass_fail = 'PASS';
   %     color = '#CCFFCC';
   % else
   %     pass_fail = 'FAIL';
   %     color = '#FF9292';
   % end
   ind = numel(tc_fail_cnt) - 5;
   if tc_fail_cnt(ind) == 0
      testcase_pass = testcase_pass + 1;
   else
      testcase_fail = testcase_fail + 1;
   end

   if testcase_pass == 1 % tot_report_cnt - 1
      pass_fail = 'PASS';
      color = '#CCFFCC';
   else
      pass_fail = 'FAIL';
      color = '#FF9292';
   end

   if strcmp(look_string, 'Look_A')
      test_case_result{2} = pass_fail;
      sitp_color{2} = color;
      str_label{1} = look_string;
   elseif strcmp(look_string, 'Look_B')
      test_case_result{3} = pass_fail;
      sitp_color{3} = color;
      str_label{2} = look_string;
   elseif strcmp(look_string, 'Look_C')
      test_case_result{4} = pass_fail;
      sitp_color{4} = color;
      str_label{3} = look_string;
   else
      test_case_result{5} = pass_fail;
      sitp_color{5} = color;
      str_label{4} = look_string;
   end

   if itr == 4
      % file_str=['AF_Output_',str_label{itr}];
      sitp_summary_string = [sitp_summary_string, '<tr>\n', ...
                             '<td bgcolor="#CCD8EE">', test_case_result{1}, '</td>\n', ...
                             '<td bgcolor=', sitp_color{2}, '><a href="./' testcase_dir_name '/Secondpass/', 'Secondpass_Output_', str_label{1}, '.html">' test_case_result{2} '</a></td>\n', ...
                             '<td bgcolor=', sitp_color{3}, '><a href="./' testcase_dir_name '/Secondpass/', 'Secondpass_Output_', str_label{2}, '.html">' test_case_result{3} '</a></td>\n', ...
                             '<td bgcolor=', sitp_color{4}, '><a href="./' testcase_dir_name '/Secondpass/', 'Secondpass_Output_', str_label{3}, '.html">' test_case_result{4} '</a></td>\n', ...
                             '<td bgcolor=', sitp_color{5}, '><a href="./' testcase_dir_name '/Secondpass/', 'Secondpass_Output_', str_label{4}, '.html">' test_case_result{5} '</a></td>\n', ...
                             '</tr>\n'];
      %             '<td bgcolor=',sitp_color{3},'<strong>',test_case_result{3},'</strong></td>\n', ...
      %             '<td bgcolor=',sitp_color{4},'<strong>',test_case_result{4},'</strong></td>\n', ...
      %             '<td bgcolor=',sitp_color{5},'<strong>',test_case_result{5},'</strong></td>\n', ...

      call_count = call_count + 1;
   end

   save('sitp_summary_string.mat', 'sitp_summary_string');
   pass_count = dir_size - sitp_error;
   if call_count == pass_count
      fid = fopen('Software_Integration_Test_Report.html', 'w+');
      fprintf(fid, sitp_summary_string);
      fclose(fid);
   end
