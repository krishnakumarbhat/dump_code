function suiteConfig = Suite_Dialog(show_dialog, suiteConfig)
   % Suite_Dialog Interactive startup dialog for RunTest_Suite_IT.
   %   The dialog lets the user configure suite-level settings before running
   %   multiple integration tests. Auto-continues with defaults after timeout.

   if nargin < 2
      suiteConfig = struct( ...
                           'sensor_type', 'FLR8', ...
                           'run_all_tests', 0, ...
                           'gen_test_profiles', 0, ...
                           'need_consolidated_report', 1, ...
                           'max_retries', 2, ...
                           'selected_tests', {{}}, ...
                           'debug_mode', 0, ...
                           'offline_mode_inject', 2, ...
                           'build_flag', 0, ...
                           'clean_build', 0);
   end

   if nargin < 1
      show_dialog = true;
   end

   if ~show_dialog
      return
   end

   defaults = suiteConfig;
   timeout_sec = 30;
   remaining_sec = timeout_sec;
   timer_handle = [];
   timer_paused = false;
   dialog_cancelled = false;

   sensor_choices = {'FLR8', 'SRR8P'};
   sensor_value = find(strcmp(sensor_choices, defaults.sensor_type), 1);
   if isempty(sensor_value)
      sensor_value = 1;
   end

   offline_labels = { ...
                     '0 - Normal MARS ADC injection', ...
                     '1 - RFFT data cube injection', ...
                     '2 - ADC data cube injection'};
   offline_values = [0, 1, 2];
   offline_value = find(offline_values == defaults.offline_mode_inject, 1);
   if isempty(offline_value)
      offline_value = 3;
   end

   % Window setup - Layout calculation:
   % Title area: ~50px, Core Settings: ~100px, Test Selection: ~180px (with listbox)
   % Execution & Recovery: ~100px, Build Settings: ~80px, Status bar: ~50px
   % Total needed: ~560px + margins = ~680px base height
   baseW = 800;
   baseH = 700;
   monitor_pos = get_best_monitor_position();
   monitorW = monitor_pos(3);
   monitorH = monitor_pos(4);
   figW = max(720, round(monitorW * 0.5));
   figH = max(620, round(monitorH * 0.55));
   ui_scale = min(figW / baseW, figH / baseH);
   scale = @(v) round(v * ui_scale);
   scaled_pos = @(x, y, w, h) [scale(x) scale(y) scale(w) scale(h)];
   figX = round(monitor_pos(1) + (monitorW - figW) / 2);
   figY = round(monitor_pos(2) + (monitorH - figH) / 2);

   dialog_handle = figure( ...
                          'Name', 'Integration Test Suite Setup', ...
                          'NumberTitle', 'off', ...
                          'MenuBar', 'none', ...
                          'ToolBar', 'none', ...
                          'Resize', 'off', ...
                          'WindowStyle', 'modal', ...
                          'Color', [0.96 0.97 0.98], ...
                          'Position', [figX figY figW figH], ...
                          'CloseRequestFcn', @cancel_dialog);

   controls = struct();
   row_h = scale(28);
   label_x = scale(24);
   control_x = scale(280);
   label_w = scale(240);
   current_y = scale(655);

   % Title
   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'text', ...
             'String', 'Integration Test Suite Configuration', ...
             'FontSize', max(10, round(14 * ui_scale)), ...
             'FontWeight', 'bold', ...
             'HorizontalAlignment', 'left', ...
             'BackgroundColor', get(dialog_handle, 'Color'), ...
             'Position', scaled_pos(24, 668, 450, 24));

   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'text', ...
             'String', 'Configure suite-level settings. Individual test dialogs will be suppressed.', ...
             'HorizontalAlignment', 'left', ...
             'FontSize', max(8, round(9 * ui_scale)), ...
             'ForegroundColor', [0.3 0.3 0.3], ...
             'BackgroundColor', get(dialog_handle, 'Color'), ...
             'Position', scaled_pos(24, 648, 700, 18));

   % === SECTION: Core Settings ===
   current_y = add_section_header('Core Settings', current_y - 30);
   current_y = add_popup_row('Sensor Type', 'sensor_type', sensor_choices, sensor_value, ...
                             'Select the radar variant (FLR8 or SRR8P).', current_y);
   current_y = add_bool_row('Debug Mode', 'debug_mode', ...
                            'Enable debug mode for all tests (keeps T32 open, skips power off).', current_y);
   current_y = add_popup_row('Offline Injection Mode', 'offline_mode_inject', offline_labels, offline_value, ...
                             'Injection mode: 0=MARS ADC, 1=RFFT datacube, 2=ADC datacube.', current_y);

   % === SECTION: Test Selection ===
   current_y = current_y - scale(10);
   current_y = add_section_header('Test Selection', current_y);
   current_y = add_bool_row('Run All Tests', 'run_all_tests', ...
                            'Run all CSV test profiles in the sensor folder.', current_y);
   current_y = add_bool_row('Generate Fresh Test Profiles', 'gen_test_profiles', ...
                            'Auto-generate test profiles from SMC parameters before running.', current_y);

   % Test case listbox
   listbox_label_y = current_y;
   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'text', ...
             'String', 'Select Test Cases (Ctrl+Click for multiple):', ...
             'HorizontalAlignment', 'left', ...
             'BackgroundColor', get(dialog_handle, 'Color'), ...
             'Position', scaled_pos(label_x, listbox_label_y, 400, 20));

   % Listbox positioned below its label
   listbox_height = 110;
   listbox_y = listbox_label_y - scale(listbox_height + 5);
   controls.test_list = uicontrol( ...
                                  'Parent', dialog_handle, ...
                                  'Style', 'listbox', ...
                                  'Max', 100, ...
                                  'Min', 0, ...
                                  'BackgroundColor', 'white', ...
                                  'Position', scaled_pos(label_x, listbox_y, 480, listbox_height));

   % Buttons for test selection (aligned to listbox)
   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'pushbutton', ...
             'String', 'Select All', ...
             'Position', scaled_pos(520, listbox_y + 80, 80, 25), ...
             'Callback', @select_all_tests);
   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'pushbutton', ...
             'String', 'Clear All', ...
             'Position', scaled_pos(520, listbox_y + 50, 80, 25), ...
             'Callback', @clear_all_tests);
   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'pushbutton', ...
             'String', 'Refresh', ...
             'Position', scaled_pos(520, listbox_y + 20, 80, 25), ...
             'Callback', @refresh_test_list);

   % Update current_y to be below the listbox
   current_y = listbox_y - scale(20);

   % === SECTION: Execution Settings ===
   current_y = add_section_header('Execution & Recovery', current_y);
   current_y = add_edit_row('Max Retries on Failure', 'max_retries', ...
                            'Number of retry attempts when a test fails (1-10).', current_y);
   current_y = add_bool_row('Generate Consolidated Report', 'need_consolidated_report', ...
                            'Generate a summary report after all tests complete.', current_y);

   % === SECTION: Build Settings ===
   current_y = current_y - scale(10);
   current_y = add_section_header('Build Settings', current_y);
   current_y = add_bool_row('Build Before Tests', 'build_flag', ...
                            'Trigger a build before running tests if needed.', current_y);
   current_y = add_bool_row('Clean Build', 'clean_build', ...
                            'Force a clean build (implies build_flag=1).', current_y);

   % === STATUS BAR AND BUTTONS (fixed at bottom) ===
   bottom_bar_y = scale(55);

   status_handle = uicontrol( ...
                             'Parent', dialog_handle, ...
                             'Style', 'text', ...
                             'String', sprintf('Auto-continue in %d seconds...', remaining_sec), ...
                             'HorizontalAlignment', 'left', ...
                             'FontWeight', 'bold', ...
                             'BackgroundColor', get(dialog_handle, 'Color'), ...
                             'Position', scaled_pos(24, 20, 400, 22));

   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'pushbutton', ...
             'String', 'Run Suite', ...
             'FontWeight', 'bold', ...
             'BackgroundColor', [0.3 0.7 0.4], ...
             'ForegroundColor', 'white', ...
             'Position', scaled_pos(590, 16, 90, 32), ...
             'Callback', @accept_dialog);

   pause_button = uicontrol( ...
                            'Parent', dialog_handle, ...
                            'Style', 'pushbutton', ...
                            'String', 'Pause Timer', ...
                            'Position', scaled_pos(490, 16, 90, 32), ...
                            'Callback', @toggle_timer_pause);

   uicontrol( ...
             'Parent', dialog_handle, ...
             'Style', 'pushbutton', ...
             'String', 'Cancel', ...
             'Position', scaled_pos(695, 16, 75, 32), ...
             'Callback', @cancel_dialog);

   % Wire up callbacks
   set(controls.sensor_type, 'Callback', @on_sensor_change);
   set(controls.run_all_tests, 'Callback', @on_run_all_change);
   set(controls.clean_build, 'Callback', @on_clean_build_change);

   % Initialize state
   on_sensor_change();
   on_run_all_change();
   on_clean_build_change();

   % Start timer
   timer_handle = timer( ...
                        'ExecutionMode', 'fixedRate', ...
                        'Period', 1, ...
                        'TimerFcn', @tick_timer);

   cleanup_obj = onCleanup(@cleanup_resources);
   start(timer_handle);
   uiwait(dialog_handle);
   clear cleanup_obj;

   if isvalid(dialog_handle)
      delete(dialog_handle);
   end

   % === NESTED HELPER FUNCTIONS ===

   function y = add_section_header(title, y)
      uicontrol( ...
                'Parent', dialog_handle, ...
                'Style', 'text', ...
                'String', title, ...
                'HorizontalAlignment', 'left', ...
                'FontWeight', 'bold', ...
                'BackgroundColor', [0.88 0.91 0.95], ...
                'Position', scaled_pos(24, y, 750, 20));
      y = y - scale(24);
   end

   function y = add_bool_row(label, field_name, tooltip, y)
      uicontrol( ...
                'Parent', dialog_handle, ...
                'Style', 'text', ...
                'String', label, ...
                'HorizontalAlignment', 'left', ...
                'BackgroundColor', get(dialog_handle, 'Color'), ...
                'Position', scaled_pos(label_x, y, label_w, 20));
      controls.(field_name) = uicontrol( ...
                                        'Parent', dialog_handle, ...
                                        'Style', 'checkbox', ...
                                        'Value', logical(defaults.(field_name)), ...
                                        'TooltipString', tooltip, ...
                                        'Position', scaled_pos(control_x, y, 24, 22));
      y = y - row_h;
   end

   function y = add_edit_row(label, field_name, tooltip, y)
      uicontrol( ...
                'Parent', dialog_handle, ...
                'Style', 'text', ...
                'String', label, ...
                'HorizontalAlignment', 'left', ...
                'BackgroundColor', get(dialog_handle, 'Color'), ...
                'Position', scaled_pos(label_x, y, label_w, 20));
      controls.(field_name) = uicontrol( ...
                                        'Parent', dialog_handle, ...
                                        'Style', 'edit', ...
                                        'String', num2str(defaults.(field_name)), ...
                                        'BackgroundColor', 'white', ...
                                        'TooltipString', tooltip, ...
                                        'HorizontalAlignment', 'left', ...
                                        'Position', scaled_pos(control_x, y, 80, 24));
      y = y - row_h;
   end

   function y = add_popup_row(label, field_name, items, value_index, tooltip, y)
      uicontrol( ...
                'Parent', dialog_handle, ...
                'Style', 'text', ...
                'String', label, ...
                'HorizontalAlignment', 'left', ...
                'BackgroundColor', get(dialog_handle, 'Color'), ...
                'Position', scaled_pos(label_x, y, label_w, 20));
      controls.(field_name) = uicontrol( ...
                                        'Parent', dialog_handle, ...
                                        'Style', 'popupmenu', ...
                                        'String', items, ...
                                        'Value', value_index, ...
                                        'TooltipString', tooltip, ...
                                        'BackgroundColor', 'white', ...
                                        'Position', scaled_pos(control_x, y, 220, 24));
      y = y - row_h;
   end

   function on_sensor_change(~, ~)
      refresh_test_list();
   end

   function on_run_all_change(~, ~)
      if logical(get(controls.run_all_tests, 'Value'))
         set(controls.test_list, 'Enable', 'off');
         select_all_tests();
      else
         set(controls.test_list, 'Enable', 'on');
      end
   end

   function on_clean_build_change(~, ~)
      if logical(get(controls.clean_build, 'Value'))
         set(controls.build_flag, 'Value', 1);
      end
   end

   function refresh_test_list(~, ~)
      sensor_name = sensor_choices{get(controls.sensor_type, 'Value')};
      folder_path = fullfile('.', 'File', 'CSV', sensor_name);
      csv_files = dir(fullfile(folder_path, '*.csv'));
      if isempty(csv_files)
         test_names = {'No CSV files found'};
      else
         [~, sort_idx] = sort({csv_files.name});
         csv_files = csv_files(sort_idx);
         test_names = {csv_files.name};
      end
      set(controls.test_list, 'String', test_names, 'Value', 1);
      setappdata(dialog_handle, 'test_files', csv_files);
   end

   function select_all_tests(~, ~)
      items = get(controls.test_list, 'String');
      if ~isempty(items) && ~strcmp(items{1}, 'No CSV files found')
         set(controls.test_list, 'Value', 1:numel(items));
      end
   end

   function clear_all_tests(~, ~)
      set(controls.test_list, 'Value', []);
   end

   function tick_timer(~, ~)
      if ~isvalid(dialog_handle)
         return
      end
      if timer_paused
         set(status_handle, 'String', sprintf('Timer paused. %d seconds remaining.', remaining_sec));
         return
      end
      remaining_sec = remaining_sec - 1;
      if remaining_sec <= 0
         accept_dialog();
      else
         set(status_handle, 'String', sprintf('Auto-continue in %d seconds...', remaining_sec));
      end
   end

   function toggle_timer_pause(~, ~)
      if timer_paused
         timer_paused = false;
         set(pause_button, 'String', 'Pause Timer');
      else
         timer_paused = true;
         set(pause_button, 'String', 'Resume');
      end
   end

   function accept_dialog(~, ~)
      cleanup_timer();
      if isvalid(dialog_handle)
         suiteConfig = read_controls();
         uiresume(dialog_handle);
      end
   end

   function cancel_dialog(~, ~)
      dialog_cancelled = true;
      cleanup_timer();
      if isvalid(dialog_handle)
         uiresume(dialog_handle);
      end
   end

   function cleanup_timer()
      if ~isempty(timer_handle) && isvalid(timer_handle)
         stop(timer_handle);
         delete(timer_handle);
         timer_handle = [];
      end
   end

   function cleanup_resources()
      cleanup_timer();
      if isvalid(dialog_handle)
         delete(dialog_handle);
      end
   end

   function config = read_controls()
      config = defaults;
      config.sensor_type = sensor_choices{get(controls.sensor_type, 'Value')};
      config.run_all_tests = logical(get(controls.run_all_tests, 'Value'));
      config.gen_test_profiles = logical(get(controls.gen_test_profiles, 'Value'));
      config.need_consolidated_report = logical(get(controls.need_consolidated_report, 'Value'));
      config.debug_mode = logical(get(controls.debug_mode, 'Value'));
      config.build_flag = logical(get(controls.build_flag, 'Value'));
      config.clean_build = logical(get(controls.clean_build, 'Value'));

      max_retries_val = str2double(strtrim(get(controls.max_retries, 'String')));
      if isnan(max_retries_val) || max_retries_val < 1
         max_retries_val = 5;
      end
      config.max_retries = min(10, max(1, round(max_retries_val)));

      config.offline_mode_inject = offline_values(get(controls.offline_mode_inject, 'Value'));

      % Get selected tests
      test_files = getappdata(dialog_handle, 'test_files');
      selected_indices = get(controls.test_list, 'Value');
      if ~isempty(test_files) && ~isempty(selected_indices)
         config.selected_tests = {test_files(selected_indices).name};
      else
         config.selected_tests = {};
      end
   end

   function monitor_pos = get_best_monitor_position()
      monitor_positions = get(groot, 'MonitorPositions');
      if isempty(monitor_positions)
         monitor_pos = [100 100 1280 720];
         return
      end
      if size(monitor_positions, 1) == 1
         monitor_pos = monitor_positions(1, :);
         return
      end
      areas = monitor_positions(:, 3) .* monitor_positions(:, 4);
      [~, idx] = max(areas);
      monitor_pos = monitor_positions(idx, :);
   end

   if dialog_cancelled
      suiteConfig = [];
   end

end
