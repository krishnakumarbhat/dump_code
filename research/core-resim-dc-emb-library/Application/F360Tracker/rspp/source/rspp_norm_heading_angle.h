   /******************************************************************************
    * Name:  RSPP_Normalize_Heading_Angle
    *   This function performs adaptive normalization of a heading angle with
    *   adjustable interval center to prevent sigma-points from exceeding
    *   boundaries. Adaptive normalization allows adjustment of the center of the
    *   normalized interval to prevent sigma-point calculations from exceeding
    *   angle boundaries during averaging operations.
    *
    * Shared Variables: None
    *
    * Parameters:
    *   angle_in        - Input angle to normalize (radians)
    *   interval_center - Center of the normalized interval (radians)
    *
    * Return Value:
    *   Normalized heading angle (radians)
    *
    * Design Information: None
    *
    * Change References: None
    *
    ******************************************************************************/
